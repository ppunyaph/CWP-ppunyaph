age = input("Please tell me your age: ")
ten_years_later = int(age) + 10
twenty_years_later = int(age) + 20
thirty_years_later = int(age) + 30
print(f"You are {age} years old.")
print(f"In 10 years, you will be {ten_years_later} years old.")
print(f"In 20 years, you will be {twenty_years_later} years old.")
print(f"In 30 years, you will be {thirty_years_later} years old.")