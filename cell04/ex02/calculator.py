first_number = int(input("Give me the first number: "))
second_number = int(input("Give me the second number: "))
print("Thank you!")
plus = first_number + second_number
print(f"{first_number} + {second_number} = {plus}")
minus = first_number - second_number
print(f"{first_number} - {second_number} = {minus}")
divide = first_number // second_number
print(f"{first_number} / {second_number} = {divide}")
times = first_number * second_number
print(f"{first_number} * {second_number} = {times}")